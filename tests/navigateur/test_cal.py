from playwright.sync_api import sync_playwright
import serveur, datetime; _srv = serveur.demarrer()
res = []
def verifie(nom, cond, detail=''):
    res.append((nom, bool(cond))); print(('OK   ' if cond else 'ÉCHEC'), nom, detail if not cond else '')
with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 1180, 'height': 820}, accept_downloads=True); pg = ctx.new_page()
    erreurs = []; pg.on('pageerror', lambda e: erreurs.append(str(e)))
    pg.goto('http://localhost:8765/'); pg.wait_for_timeout(900)
    pg.get_by_role('button', name='Calendrier').click(); pg.wait_for_timeout(300)
    fen = pg.locator('[role=dialog][aria-label=Calendrier]')
    verifie('le calendrier s’ouvre en fenêtre', fen.count() == 1)
    mois = datetime.date.today().strftime('%m')
    verifie('mois en cours affiché', 'Aucune publication programmée ce mois-ci' in fen.inner_text())
    verifie('aujourd’hui marqué', fen.locator('.calendrier-case.aujourdhui').count() == 1)
    verifie('l’article d’exemple est à programmer', fen.locator('.calendrier-a-programmer', has_text='Le silence au travail').count() == 1)
    fen.locator('.calendrier-a-programmer', has_text='Le silence au travail').click(); pg.wait_for_timeout(150)
    verifie('consigne : toucher un jour', 'Touche maintenant un jour du calendrier.' in fen.inner_text())
    jour = fen.locator('.calendrier-case').nth(21).locator('.calendrier-numero')
    etiquette = jour.get_attribute('aria-label'); jour.click(); pg.wait_for_timeout(300)
    verifie('programmé sur ce jour', fen.locator('.calendrier-case').nth(21).locator('.calendrier-item', has_text='Le silence au travail').count() == 1, etiquette)
    fiche = fen.locator('.calendrier-fiche')
    verifie('fiche ouverte : date, heure, réseau', fiche.count() == 1 and fiche.locator('input[type=date]').count() == 1 and fiche.locator('input[type=time]').input_value() == '09:00')
    verifie('les deux boutons décidés', fiche.get_by_role('button', name='Programmer un rappel').count() == 1 and fiche.get_by_role('button', name='Programmer une publication automatique').is_disabled())
    with pg.expect_download() as tel:
        fiche.get_by_role('button', name='Programmer un rappel').click()
    d = tel.value; chemin = d.path(); ics = open(chemin, encoding='utf-8', newline='').read()
    verifie('fichier de rappel .ics', d.suggested_filename.endswith('.ics') and 'BEGIN:VEVENT' in ics and 'TRIGGER:PT0M' in ics and 'Publier « Le silence au travail » sur' in ics, d.suggested_filename)
    date_ics = [l for l in ics.split('\r\n') if l.startswith('DTSTART:')][0]
    verifie('date et heure du rappel', date_ics.endswith('T090000'), date_ics)
    pg.wait_for_timeout(200)
    verifie('rappel signalé dans la fiche', 'Rappel programmé.' in fiche.inner_text() and fiche.get_by_role('button', name='Programmer un nouveau rappel').count() == 1)
    fiche.locator('input[type=time]').fill('10:30'); pg.wait_for_timeout(200)
    verifie('changer l’heure invalide l’ancien rappel', 'Rappel programmé.' not in fiche.inner_text() and fiche.get_by_role('button', name='Programmer un rappel').count() == 1)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    verifie('Échap ferme la fenêtre', pg.locator('[role=dialog][aria-label=Calendrier]').count() == 0)
    carte = pg.locator('main').inner_text()
    verifie('la carte de l’article indique « Programmé »', 'Programmé · ' in carte, carte[:300])
    pg.reload(); pg.wait_for_timeout(1000)
    verifie('programmation enregistrée (après rechargement)', 'Programmé · ' in pg.locator('main').inner_text())
    pg.get_by_role('button', name='Calendrier').click(); pg.wait_for_timeout(300)
    fen = pg.locator('[role=dialog][aria-label=Calendrier]')
    fen.locator('.calendrier-item', has_text='Le silence au travail').click(); pg.wait_for_timeout(200)
    verifie('heure gardée', fen.locator('.calendrier-fiche input[type=time]').input_value() == '10:30')
    fen.get_by_role('button', name='Mois suivant').click(); pg.wait_for_timeout(150)
    verifie('mois suivant sans publication', 'Aucune publication programmée ce mois-ci' in fen.inner_text())
    fen.get_by_role('button', name='Aujourd’hui').click(); pg.wait_for_timeout(150)
    fen.locator('.calendrier-item', has_text='Le silence au travail').click(); pg.wait_for_timeout(150)
    fen.locator('.calendrier-fiche').get_by_role('button', name='Déprogrammer').click(); pg.wait_for_timeout(250)
    verifie('déprogrammer : de retour dans « À programmer »', fen.locator('.calendrier-a-programmer', has_text='Le silence au travail').count() == 1 and fen.locator('.calendrier-item').count() == 0)
    verifie('le message « déprogrammé » reste visible au-dessus de la fenêtre', pg.locator('.message').is_visible())
    pg.locator('.message').get_by_role('button', name='Annuler').click(); pg.wait_for_timeout(250)
    verifie('« Annuler » reprogramme', fen.locator('.calendrier-item', has_text='Le silence au travail').count() == 1)
    fen.get_by_role('button', name='Fermer le calendrier').click(); pg.wait_for_timeout(200)
    verifie('× ferme la fenêtre', pg.locator('[role=dialog][aria-label=Calendrier]').count() == 0)
    pg.get_by_role('button', name='Aide sur cet écran').click(); pg.wait_for_timeout(150)
    verifie('aide : calendrier et version', 'Programmer un rappel' in pg.locator('.panneau-aide').inner_text() and 'version 2026-10-28.11' in pg.locator('.panneau-aide').inner_text())
    print('erreurs JS :', erreurs); verifie('aucune erreur JavaScript', not erreurs)
    # Capture en sombre
    pg2 = b.new_page(viewport={'width': 1180, 'height': 820}, color_scheme='dark'); pg2.goto('http://localhost:8765/'); pg2.wait_for_timeout(900)
    pg2.get_by_role('button', name='Calendrier').click(); pg2.wait_for_timeout(300)
    pg2.locator('.calendrier-a-programmer').first.click(); pg2.locator('.calendrier-case').nth(21).locator('.calendrier-numero').click(); pg2.wait_for_timeout(300); pg2.screenshot(path='cal-sombre.png')
    b.close()
print(sum(1 for _, o in res if o), '/', len(res), 'vérifications réussies')
