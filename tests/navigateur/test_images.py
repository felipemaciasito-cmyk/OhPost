from playwright.sync_api import sync_playwright
import serveur; _srv = serveur.demarrer()
res = []
def verifie(nom, cond, detail=''):
    res.append((nom, bool(cond))); print(('OK   ' if cond else 'ÉCHEC'), nom, detail if not cond else '')
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 1180, 'height': 820})
    erreurs = []; pg.on('pageerror', lambda e: erreurs.append(str(e)))
    pg.goto('http://localhost:8765/'); pg.wait_for_timeout(900)
    pg.get_by_text('Le silence au travail').first.click(); pg.wait_for_timeout(300)
    pg.locator('nav.etapes .etape').nth(1).click(); pg.wait_for_timeout(700)
    toile = lambda: pg.locator('canvas[aria-label="Page 1"]').evaluate('(c) => c.toDataURL()')
    depart = toile()
    pg.get_by_role('button', name='Insertion', exact=True).click(); pg.wait_for_timeout(150)
    pg.get_by_role('menuitem', name='Fleurs', exact=True).click(); pg.wait_for_timeout(400)
    verifie('fleurs ajoutées et choisies', pg.locator('.barre-image').count() == 1 and 'Fleurs' in pg.locator('.barre-image').inner_text() and toile() != depart)
    apres_ajout = toile()
    box = pg.locator('.selection-image').bounding_box()
    cx, cy = box['x'] + box['width'] / 2, box['y'] + box['height'] / 2
    # Le centre des fleurs peut être sous le texte : on les prend par leur bord bas.
    yb = box['y'] + box['height'] - 8
    pg.mouse.move(cx, yb); pg.mouse.down(); pg.mouse.move(cx - 60, yb + 40, steps=6); pg.mouse.move(cx - 120, yb + 70, steps=6); pg.mouse.up(); pg.wait_for_timeout(400)
    box2 = pg.locator('.selection-image').bounding_box()
    verifie('glisser déplace les fleurs', box2 and box2['x'] < box['x'] - 80 and box2['y'] > box['y'] + 40, (box, box2))
    fermer_message = lambda: pg.locator('.message').get_by_role('button', name='Fermer').click() if pg.locator('.message').count() else None
    fermer_message(); pg.wait_for_timeout(200)
    h = pg.locator('.poignee-image').bounding_box()
    pg.mouse.move(h['x'] + h['width'] / 2, h['y'] + h['height'] / 2); pg.mouse.down(); pg.mouse.move(h['x'] - 40, h['y'], steps=8); pg.mouse.up(); pg.wait_for_timeout(400)
    box3 = pg.locator('.selection-image').bounding_box()
    verifie('la poignée réduit la taille', box3['width'] < box2['width'] - 25, (box2['width'], box3['width']))
    pg.locator('.barre-image').get_by_role('button', name='Verrouiller').click(); pg.wait_for_timeout(300)
    verifie('verrouillé : plus de cadre ni de barre', pg.locator('.barre-image').count() == 0 and 'Verrouillé' in pg.locator('.message').inner_text())
    pg.mouse.click(box3['x'] + box3['width'] / 2, box3['y'] + box3['height'] / 2); pg.wait_for_timeout(300)
    verifie('un élément verrouillé ne se choisit plus sur la page', pg.locator('.barre-image').count() == 0)
    pg.get_by_role('button', name='Page', exact=True).click(); pg.wait_for_timeout(150)
    pg.get_by_role('menuitem', name='Logo et fleurs').click(); pg.wait_for_timeout(200)
    liste = pg.locator('.liste-images').inner_text()
    verifie('menu Page › Logo et fleurs : élément verrouillé listé', 'Fleurs · verrouillé' in liste, liste)
    pg.get_by_role('button', name='Déverrouiller Fleurs').click(); pg.wait_for_timeout(300)
    verifie('déverrouiller depuis la liste', 'Fleurs · verrouillé' not in pg.locator('.liste-images').inner_text())
    pg.keyboard.press('Escape'); pg.wait_for_timeout(150)
    pg.get_by_role('button', name='Page', exact=True).click(); pg.wait_for_timeout(150)
    pg.get_by_role('menuitem', name='Logo et fleurs').click(); pg.wait_for_timeout(200)
    pg.locator('.liste-images .nom-image').first.click(); pg.wait_for_timeout(300)
    verifie('déverrouillé : on le choisit depuis la liste', pg.locator('.barre-image').count() == 1)
    fermer_message(); pg.wait_for_timeout(200)
    pg.locator('.barre-image').get_by_role('button', name='Supprimer').click(); pg.wait_for_timeout(300)
    msg = pg.locator('.message').inner_text() if pg.locator('.message').count() else ''
    verifie('supprimer', pg.locator('.barre-image').count() == 0 and 'retiré' in msg, msg)
    pg.get_by_role('button', name='Page', exact=True).click(); pg.wait_for_timeout(150)
    pg.get_by_role('menuitem', name='Logo et fleurs').click(); pg.wait_for_timeout(200)
    pg.get_by_role('button', name='Revenir au placement du gabarit').click(); pg.wait_for_timeout(400)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(300)
    verifie('revenir au placement du gabarit : slide d’origine', toile() == depart)
    # Le texte reste prioritaire : un clic sur le titre choisit le bloc, pas l'image
    pg.get_by_role('button', name='Insertion', exact=True).click(); pg.get_by_role('menuitem', name='Fleurs', exact=True).click(); pg.wait_for_timeout(300)
    pg.mouse.click(600, 590); pg.wait_for_timeout(300)
    verifie('toucher le texte choisit le bloc, pas les fleurs derrière', pg.locator('.barre-image').count() == 0 and pg.locator('.selection-bloc').count() >= 1)
    print('erreurs JS :', erreurs); verifie('aucune erreur JavaScript', not erreurs)
    b.close()
print(sum(1 for _, o in res if o), '/', len(res), 'vérifications réussies')
