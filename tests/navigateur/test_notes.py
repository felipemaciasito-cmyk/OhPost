from playwright.sync_api import sync_playwright
import serveur, json; _srv = serveur.demarrer()
A = json.load(open(serveur.DONNEES + '/articles.json'))
texte = '\n\n'.join(A['SA__jour_chez_mes_parents'])
res = []
def verifie(nom, cond, detail=''):
    res.append((nom, bool(cond))); print(('OK   ' if cond else 'ÉCHEC'), nom, detail if not cond else '')
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 1180, 'height': 900})
    erreurs = []; pg.on('pageerror', lambda e: erreurs.append(str(e)))
    pg.goto('http://localhost:8765/'); pg.wait_for_timeout(900)
    pg.get_by_role('button', name='Nouvel article').first.click(); pg.wait_for_timeout(300)
    zone = pg.locator('#texte-modele'); zone.click(); pg.keyboard.insert_text(texte); pg.wait_for_timeout(300)
    boite = pg.locator('.notes-travail')
    verifie('3 notes signalées', boite.count() == 1 and '3 lignes ressemblent à des notes de travail' in boite.inner_text(), boite.inner_text() if boite.count() else '(rien)')
    verifie('les trois sont cochées', boite.locator('input[type=checkbox]:checked').count() == 3)
    verifie('la typographie est aussi annoncée', 'Typographie corrigée' in pg.locator('main').inner_text())
    boite.locator('label', has_text='Titre commun').locator('input').click(); pg.wait_for_timeout(150)
    verifie('bouton mis à jour', pg.get_by_role('button', name='Retirer les 2 lignes cochées').count() == 1)
    pg.get_by_role('button', name='Retirer les 2 lignes cochées').click(); pg.wait_for_timeout(250)
    v = zone.input_value()
    verifie('2 lignes retirées, « Titre commun » gardé', not v.startswith('Posts LinkedIn') and '(est-ce qu' not in v and v.startswith('Titre commun'), v[:80])
    verifie('plus de signalement pour la ligne gardée', pg.locator('.notes-travail').count() == 0)
    verifie('message avec Annuler', '2 lignes retirées' in pg.locator('main').inner_text())
    pg.locator('main p', has_text='2 lignes retirées').get_by_role('button', name='Annuler').click(); pg.wait_for_timeout(250)
    verifie('Annuler rend le texte collé', zone.input_value().startswith('Posts LinkedIn') and pg.locator('.notes-travail').count() == 1)
    pg.get_by_role('button', name='Tout garder').click(); pg.wait_for_timeout(200)
    verifie('Tout garder : signalement retiré, texte intact', pg.locator('.notes-travail').count() == 0 and zone.input_value().startswith('Posts LinkedIn'))
    # Recoller proprement et retirer les 3, puis créer
    zone.evaluate('(el) => el.select()'); pg.keyboard.insert_text('x'); pg.wait_for_timeout(100)
    zone.evaluate('(el) => el.select()'); pg.keyboard.insert_text(texte); pg.wait_for_timeout(300)
    verifie('nouveau collage : les lignes gardées ne sont plus signalées', pg.locator('.notes-travail').count() == 0)
    b.close()
    # Article sans notes : aucun signalement
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 1180, 'height': 900}); pg.on('pageerror', lambda e: erreurs.append(str(e)))
    pg.goto('http://localhost:8765/'); pg.wait_for_timeout(900)
    pg.get_by_role('button', name='Nouvel article').first.click(); pg.wait_for_timeout(300)
    zone = pg.locator('#texte-modele'); zone.click(); pg.keyboard.insert_text('\n\n'.join(A['Clara'])); pg.wait_for_timeout(300)
    verifie('article sans notes : rien de signalé', pg.locator('.notes-travail').count() == 0)
    zone.evaluate('(el) => el.select()'); pg.keyboard.insert_text(texte); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='Retirer les 3 lignes cochées').click(); pg.wait_for_timeout(250)
    pg.get_by_role('button', name='Continuer', exact=True).click(); pg.wait_for_timeout(300); _q = pg.get_by_role('dialog', name='Ton nouvel article'); _q.get_by_role('button', name='Portrait · 4:5').click(); _q.get_by_role('button', name='Commencer').click(); pg.wait_for_timeout(700)
    pg.get_by_role('button', name='Texte').first.click(); pg.wait_for_timeout(300)
    val = pg.locator('textarea.editeur-zone').input_value()
    verifie('article créé sans les notes', val.startswith('«\u00a0Vous avez fait un séjour') and 'Posts LinkedIn' not in val, val[:60])
    pg.screenshot(path='notes.png')
    print('erreurs JS :', erreurs); verifie('aucune erreur JavaScript', not erreurs)
    b.close()
print(sum(1 for _, o in res if o), '/', len(res), 'vérifications réussies')
