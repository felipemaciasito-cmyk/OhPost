from playwright.sync_api import sync_playwright
import serveur, json; _srv = serveur.demarrer()
A = json.load(open(serveur.DONNEES + '/articles.json')); texte = '\n\n'.join(A['Clara'])
res = []
def verifie(nom, cond, detail=''):
    res.append((nom, bool(cond))); print(('OK   ' if cond else 'ÉCHEC'), nom, detail if not cond else '')
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 1180, 'height': 900})
    erreurs = []; pg.on('pageerror', lambda e: erreurs.append(str(e)))
    pg.goto('http://localhost:8765/'); pg.wait_for_timeout(900)
    pg.get_by_role('button', name='Nouvel article').first.click(); pg.wait_for_timeout(300)
    fe = pg.locator('[role=dialog]')
    verifie('sans texte : impossible de continuer', pg.get_by_role('button', name='Continuer', exact=True).is_disabled())
    pg.locator('#texte-modele').click(); pg.keyboard.insert_text(texte); pg.wait_for_timeout(600)
    pg.get_by_role('button', name='Continuer', exact=True).click(); pg.wait_for_timeout(300); _q = pg.get_by_role('dialog', name='Ton nouvel article'); _q.get_by_role('button', name='Portrait · 4:5').click(); _q.get_by_role('button', name='Commencer').click(); pg.wait_for_timeout(700)
    # Le logo et les fleurs se placent dans la fenêtre de mise en page, ouverte au premier passage à l'étape 2.
    pg.get_by_role('button', name='Continuer : Mise en page').click(); pg.wait_for_timeout(600)
    fe = pg.locator('[role=dialog]')
    verifie('par défaut : ne rien changer', fe.get_by_role('button', name='Ne pas changer').get_attribute('aria-pressed') in ('true', None) and fe.locator('.schema-logo').count() == 0)
    fe.get_by_role('button', name='Je les place').click(); pg.wait_for_timeout(400)
    sch = fe.locator('.schema-logo')
    nb = sch.locator('.schema-vignette').count()
    verifie('schéma avec les vraies pages', sch.count() == 1 and nb >= 4 and sch.locator('.schema-slide canvas').count() == 1, nb)
    verifie('départ : logo partout, fleurs couverture et fin', 'Logo sur %d pages, fleurs sur 2 pages' % nb in sch.inner_text(), sch.inner_text()[-160:])
    logo = sch.locator('.schema-element').nth(1); bx = logo.bounding_box()
    logo.scroll_into_view_if_needed(); bx = logo.bounding_box()
    pg.mouse.move(bx['x'] + bx['width'] / 2, bx['y'] + bx['height'] / 2); pg.mouse.down(); pg.mouse.move(bx['x'] - 100, bx['y'] - 150, steps=8); pg.mouse.up(); pg.wait_for_timeout(300)
    bx2 = sch.locator('.schema-element').nth(1).bounding_box()
    verifie('glisser le logo sur le schéma', bx2['x'] < bx['x'] - 60 and bx2['y'] < bx['y'] - 90, (bx, bx2))
    sch.get_by_role('button', name='Fleurs', exact=True).first.click(); pg.wait_for_timeout(150)
    sch.get_by_role('button', name='Aucune').click(); pg.wait_for_timeout(300)
    verifie('raccourci « Aucune » pour les fleurs', 'fleurs sur 0 page' in sch.inner_text())
    sch.get_by_role('button', name='Mettre les fleurs sur la page 2').click(); pg.wait_for_timeout(300)
    verifie('slide par slide : fleurs sur la page 2', 'fleurs sur 1 page' in sch.inner_text() and sch.get_by_role('button', name='Retirer les fleurs sur la page 2').count() == 1)
    sch.get_by_role('button', name='Retirer le logo sur la page 3').click(); pg.wait_for_timeout(300)
    verifie('slide par slide : logo retiré de la page 3', 'Logo sur %d pages' % (nb - 1) in sch.inner_text())
    fe.get_by_role('button', name='Appliquer').click(); pg.wait_for_timeout(900)
    def liste(n):
        pg.get_by_role('button', name=f'Page {n}', exact=True).click() if pg.get_by_role('button', name=f'Page {n}', exact=True).count() else None
        pg.wait_for_timeout(150)
        pg.get_by_role('menuitem', name='Logo et fleurs').click(); pg.wait_for_timeout(200)
        t = pg.locator('.liste-images').inner_text(); pg.keyboard.press('Escape'); pg.wait_for_timeout(150); return t
    t1 = liste(1)
    verifie('slide 1 : logo seulement', 'Logo' in t1 and 'Fleurs' not in t1, t1)
    pg.get_by_role('button', name='Affichage', exact=True).click(); pg.get_by_role('menuitem', name='Aller à la page').click(); pg.wait_for_timeout(150)
    pg.locator('[role^=menuitem]').filter(has_text='Page 2').first.click(); pg.wait_for_timeout(300)
    t2 = liste(2)
    verifie('slide 2 : logo et fleurs', 'Logo' in t2 and 'Fleurs' in t2, t2)
    print('erreurs JS :', erreurs); verifie('aucune erreur JavaScript', not erreurs)
    b.close()
print(sum(1 for _, o in res if o), '/', len(res), 'vérifications réussies')
