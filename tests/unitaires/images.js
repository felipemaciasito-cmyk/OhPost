const M = require('../../moteur.js');
let ok = 0, ko = 0; const eq = (n, a, b) => { const A = JSON.stringify(a), B = JSON.stringify(b); if (A === B) ok++; else { ko++; console.log('ÉCHEC', n, '\n  obtenu :', A, '\n  attendu:', B); } };
const police = { mesurer: (t, taille) => t.length * taille * 0.5, asc: 0.8, desc: 0.2 };
const cp = () => police;
const couv = { role: 'Couverture', gabarit: 'V5', blocs: [{ style: 'titre', texte: 'Je crois que je vais démissionner.' }] };
const auto = M.composer(couv, 'carre', 'bleu', cp, {});
const imgsAuto = auto.elements.filter((e) => e.type === 'image');
eq('V5 : des fleurs automatiques', imgsAuto.map((e) => e.cle), ['fleurs']);
const conv = M.imagesDe(auto);
eq('conversion en placement à la main', [conv.length, conv[0].type, conv[0].w > 0 && conv[0].w < 1], [1, 'fleurs', true]);
const manuel = M.composer({ ...couv, images: conv.concat([{ type: 'logo', x: 0.1, y: 0.8, w: 0.25, verrou: true }]) }, 'carre', 'bleu', cp, {});
const im = manuel.elements.filter((e) => e.type === 'image');
eq('fleurs à la même place, logo ajouté', [im.length, im[0].x === imgsAuto[0].x && im[0].y === imgsAuto[0].y, im[1].cle.startsWith('logo'), im[1].x, im[1].verrou], [2, true, true, 108, true]);
eq('images dessinées avant (derrière) le texte', manuel.elements.findIndex((e) => e.type === 'image') < manuel.elements.findIndex((e) => e.type === 'ligne'), true);
const vide = M.composer({ ...couv, images: [] }, 'carre', 'bleu', cp, {});
eq('liste vide : plus aucune image', vide.elements.filter((e) => e.type === 'image').length, 0);
const fin = M.composer({ role: 'Texte', gabarit: 'F1', signature: true, blocs: [{ style: 'corps', texte: 'Fin.' }] }, 'carre', 'blanc', cp, { index: 5, total: 6 });
eq('fin : logo et fleurs automatiques convertibles', M.imagesDe(fin).map((x) => x.type).sort(), ['fleurs', 'logo']);
console.log(`${ok} réussis, ${ko} échecs`);
